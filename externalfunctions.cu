__global__ void self_grav_pp_kernel_tiled(
    const struct gravity_gpu_values_send *__restrict__ gravity_gpu_values_send_d,
    struct gravity_gpu_values_recv *__restrict__ gravity_gpu_values_recv_d,
    const int *__restrict__ counts_d,
    const int *__restrict__ offsets_d,
    const int *__restrict__ active_counts_d,
    const int *__restrict__ active_offsets_d,
    const int *__restrict__ active_index_d,
    const float *__restrict__ rmax_d,
    float r_s_inv,
    const int periodic,
    float min_trunc,
    int ncells,
    int max_cell_size) {

  const int cell = blockIdx.x;
  if (cell >= ncells) return;

  const int counts = counts_d[cell];
  if (counts <= 0) return;

  const int active_count = active_counts_d[cell];
  if (active_count <= 0) return;

  const int cell_offset = offsets_d[cell];

  const float factor =
      gravity_gpu_values_send_d[cell_offset].flags0.w ? 1.f : 0.f;
  if (factor == 0.f) return;

  const int use_full = (!periodic) || (rmax_d[cell] <= min_trunc);

  const int active_slot = blockIdx.y * blockDim.x + threadIdx.x;
  const int valid_target = (active_slot < active_count);

  const int active_base = active_offsets_d[cell];
  int local_pid = 0;
  if (valid_target) {
    local_pid = active_index_d[active_base + active_slot];
  }

  float xi = 0.f, yi = 0.f, zi = 0.f, hi = 0.f;

  if (valid_target) {
    const gravity_gpu_values_send pi =
        gravity_gpu_values_send_d[cell_offset + local_pid];
    xi = pi.values_i.x;
    yi = pi.values_i.y;
    zi = pi.values_i.z;
    hi = pi.values_i.w;
  }

  float a_x = 0.f, a_y = 0.f, a_z = 0.f, pot = 0.f;

  extern __shared__ gravity_gpu_values_send send[];

  for (int i0 = 0; i0 < counts; i0 += blockDim.x) {
    const int i = i0 + threadIdx.x;
    if (i < counts) {
      send[threadIdx.x] = gravity_gpu_values_send_d[cell_offset + i];
    }
    __syncthreads();

    const int tile = min(blockDim.x, counts - i0);

    if (valid_target) {
      for (int j = 0; j < tile; j++) {
        const int src_local_pid = i0 + j;

        if (local_pid == src_local_pid) continue;

        const gravity_gpu_values_send pj = send[j];
        const float mass_j = pj.mass.y;

        const float dx = pj.values_j.x - xi;
        const float dy = pj.values_j.y - yi;
        const float dz = pj.values_j.z - zi;

        const float r2 = dx * dx + dy * dy + dz * dz;
        const float h = max(hi, pj.values_j.w);
        const float h2 = h * h;
        const float h_inv = 1.f / h;
        const float h_inv_3 = h_inv * h_inv * h_inv;

        float f_ij, pot_ij;

        if (use_full) {
          iact_grav_pp_full(r2, h2, h_inv, h_inv_3, mass_j, &f_ij, &pot_ij);
        } else {
          iact_grav_pp_truncated(
              r2, h2, h_inv, h_inv_3, mass_j, r_s_inv, &f_ij, &pot_ij);
        }

        a_x += f_ij * dx;
        a_y += f_ij * dy;
        a_z += f_ij * dz;
        pot += pot_ij;
      }
    }

    __syncthreads();
  }

  if (valid_target) {
	  const int out = active_base + active_slot;
	  gravity_gpu_values_recv_d[out].values_i.x = a_x * factor;
	  gravity_gpu_values_recv_d[out].values_i.y = a_y * factor;
	  gravity_gpu_values_recv_d[out].values_i.z = a_z * factor;
	  gravity_gpu_values_recv_d[out].values_i.w = pot * factor;
 }
}
/**
 * @brief Compute direct pair-cell P-P gravity interactions for one side of each packed pair.
 *
 * Each block processes one packed cell pair and accumulates the force and
 * potential on either the i-side or j-side particles, depending on swap.
 *
 * @param send Device input buffer for packed particle pairs.
 * @param recv Device output buffer for accelerations and potential.
 * @param periodic Whether periodic boundary conditions are enabled.
 * @param r_s_inv Inverse splitting scale for truncated periodic forces.
 * @param symmetric Whether both sides of the pair are updated.
 * @param swap Selects which side of the packed pair is updated.
 * @param dim_0 Domain size in the x dimension.
 * @param dim_1 Domain size in the y dimension.
 * @param dim_2 Domain size in the z dimension.
 * @param max_cell_size Maximum number of particles per packed cell.
 * @param ncells Number of packed cell slots in the batch.
 */
__global__ void pair_grav_pp_kernel(
    const gravity_gpu_values_send *send,
    gravity_gpu_values_recv *recv,
    int periodic, float r_s_inv,
    int symmetric,
    int swap, // 0: compute i-side (base_i interacts with base_j) 1: compute j-side (base_j interacts with base_i)
    float dim_0, float dim_1, float dim_2,
    int max_cell_size, int ncells){
    
  int pair_id = blockIdx.x;
  int base0 = (2 * pair_id) * max_cell_size;
  int base1 = base0 + max_cell_size;

  int base_i = swap ? base1 : base0;
  int base_j = swap ? base0 : base1;

  int count_i = send[base_i].flags0.z;
  int count_j = send[base_j].flags0.z;

  int pid = blockIdx.y * blockDim.x + threadIdx.x;
  if (pid >= count_i) return;

  // Only update if this target cell is active (matches CPU)
  int ci_active = send[base_i].flags0.w;
  if (!ci_active) return;

  // active particle gating
  int act = (send[base_i + pid].flags0.x > 0);
  if (!act) return;

  float xi = send[base_i + pid].values_i.x;
  float yi = send[base_i + pid].values_i.y;
  float zi = send[base_i + pid].values_i.z;
  float hi = send[base_i + pid].values_i.w;

  float ax=0.f, ay=0.f, az=0.f, pot=0.f;

  int use_full = send[base_i].flags1.x;   // 1 full, 0 truncated

  for (int pjd = 0; pjd < count_j; ++pjd) {

    float xj = send[base_j + pjd].values_i.x;
    float yj = send[base_j + pjd].values_i.y;
    float zj = send[base_j + pjd].values_i.z;
    float mj = send[base_j + pjd].mass.x; 

    float dx = xj - xi;
    float dy = yj - yi;
    float dz = zj - zi;

    if (periodic) {
      dx = nearestf1(dx, dim_0);
      dy = nearestf1(dy, dim_1);
      dz = nearestf1(dz, dim_2);
    }

    float r2 = dx*dx + dy*dy + dz*dz;

    float hj = send[base_j + pjd].values_i.w;
    float h = max(hi, hj);
    float h2 = h*h;
    float hinv = 1.f / h;
    float hinv3 = hinv*hinv*hinv;

    float fij, potij;
    if (use_full) {
      iact_grav_pp_full(r2, h2, hinv, hinv3, mj, &fij, &potij);
    } else {
      iact_grav_pp_truncated(r2, h2, hinv, hinv3, mj, r_s_inv, &fij, &potij);
    }

    ax += fij * dx;
    ay += fij * dy;
    az += fij * dz;
    pot += potij;
  }

  recv[base_i + pid].values_i.x += ax;
  recv[base_i + pid].values_i.y += ay;
  recv[base_i + pid].values_i.z += az;
  recv[base_i + pid].values_i.w += pot;
}

/**
 * @brief Compute tiled direct pair-cell P-P gravity interactions for one side of each packed pair.
 *
 * This kernel is the shared-memory tiled variant of @ref pair_grav_pp_kernel,
 * loading source-particle data in tiles to reduce global memory traffic.
 *
 * @param send Device input buffer for packed particle pairs.
 * @param recv Device output buffer for accelerations and potential.
 * @param periodic Whether periodic boundary conditions are enabled.
 * @param r_s_inv Inverse splitting scale for truncated periodic forces.
 * @param symmetric Whether both sides of the pair are updated.
 * @param swap Selects which side of the packed pair is updated.
 * @param dim_0 Domain size in the x dimension.
 * @param dim_1 Domain size in the y dimension.
 * @param dim_2 Domain size in the z dimension.
 * @param max_cell_size Maximum number of particles per packed cell.
 * @param ncells Number of packed cell slots in the batch.
 */
__global__ void pair_grav_pp_kernel_tiled(
    const gravity_gpu_values_send *send,
    const float4 *send_pos_mass,
    const float *send_h,
    gravity_gpu_values_recv *recv,
    const int *pair_counts_d,
    const int *pair_offsets_d,
    const int *pair_active_counts_d,
    const int *pair_active_offsets_d,
    const int *pair_active_index_d,
    int periodic, float r_s_inv,
    int swap,
    float dim_0, float dim_1, float dim_2,
    int ncells) {

  int pair_id = blockIdx.x;
  int slot0 = 2 * pair_id;
  int slot1 = slot0 + 1;
  
  if (slot1 >= ncells) return;

  int base0 = pair_offsets_d[slot0];
  int base1 = pair_offsets_d[slot1];

  int base_i = swap ? base1 : base0;
  int base_j = swap ? base0 : base1;

  int count_i = swap ? pair_counts_d[slot1] : pair_counts_d[slot0];
  int count_j = swap ? pair_counts_d[slot0] : pair_counts_d[slot1];

  int pid = blockIdx.y * blockDim.x + threadIdx.x;
  const int target_slot = swap ? slot1 : slot0;
  const int active_count_i = pair_active_counts_d[target_slot];
  if (active_count_i <= 0) return;
  int valid_pid = (pid < active_count_i);

  int ci_active = send[base_i].flags0.w;
  if (!ci_active) return;

  const int active_base = pair_active_offsets_d[target_slot];
  const int local_pid_i =
    valid_pid ? pair_active_index_d[active_base + pid] : 0;

  float xi = 0.f;
  float yi = 0.f;
  float zi = 0.f;
  float hi = 0.f;

  if (valid_pid) {
    xi = send[base_i + local_pid_i].values_i.x;
    yi = send[base_i + local_pid_i].values_i.y;
    zi = send[base_i + local_pid_i].values_i.z;
    hi = send[base_i + local_pid_i].values_i.w;
  }

  float ax = 0.f, ay = 0.f, az = 0.f, pot = 0.f;

  int use_full = send[base_i].flags1.x;

  //extern __shared__ gravity_gpu_values_send sh_j[];
  extern __shared__ char smem[];

	float4 *sh_pos_mass = (float4*)smem;
	float *sh_h = (float*)&sh_pos_mass[blockDim.x];

	for (int j0 = 0; j0 < count_j; j0 += blockDim.x) {

	  int jload = j0 + threadIdx.x;

	  if (jload < count_j) {
	    sh_pos_mass[threadIdx.x] = send_pos_mass[base_j + jload];
	    sh_h[threadIdx.x] = send_h[base_j + jload];
	  }

	  __syncthreads();

	  int tile = min(blockDim.x, count_j - j0);

	  if (valid_pid) {
	    for (int j = 0; j < tile; ++j) {
	      float4 pj = sh_pos_mass[j];

		float xj = pj.x;
		float yj = pj.y;
		float zj = pj.z;
		float mj = pj.w;

		float hj = sh_h[j];

        float dx = xj - xi;
        float dy = yj - yi;
        float dz = zj - zi;

        if (periodic) {
          dx = nearestf1(dx, dim_0);
          dy = nearestf1(dy, dim_1);
          dz = nearestf1(dz, dim_2);
        }

        float r2 = dx * dx + dy * dy + dz * dz;

        //float hj = pj.values_i.w;
        float h = max(hi, hj);
        float h2 = h * h;
        float hinv = 1.f / h;
        float hinv3 = hinv * hinv * hinv;

        float fij, potij;
        if (use_full) {
          iact_grav_pp_full(r2, h2, hinv, hinv3, mj, &fij, &potij);
        } else {
          iact_grav_pp_truncated(r2, h2, hinv, hinv3, mj, r_s_inv, &fij, &potij);
        }

        ax += fij * dx;
        ay += fij * dy;
        az += fij * dz;
        pot += potij;
      }
    }
    __syncthreads();
  }

  if (valid_pid) {
    const int out = active_base + pid;

	recv[out].values_i.x = ax;
	recv[out].values_i.y = ay;
	recv[out].values_i.z = az;
	recv[out].values_i.w = pot;;
  }
}
