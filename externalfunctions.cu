/**
 * @brief Compute full self-cell P-P gravity interactions using shared-memory tiling.
 *
 * This kernel is the tiled variant of the self-cell full-force interaction,
 * reusing source-particle data from shared memory to reduce global memory traffic.
 *
 * @param gravity_gpu_values_send_d Device input buffer for packed particles.
 * @param gravity_gpu_values_recv_d Device output buffer for accelerations and potential.
 * @param r_s_inv Inverse splitting scale (unused for the full interaction path).
 * @param gcount_i Number of particles in the cell.
 * @param gcount_padded_i Padded particle count in the cell.
 * @param periodic Whether periodic boundary conditions are enabled.
 * @param max_r_decision Whether the full interaction path should be used.
 * @param ncells Number of packed cells in the batch.
 */
__global__ void doself_grav_pp_full_new_refactor_tiled(
    const struct gravity_gpu_values_send *gravity_gpu_values_send_d,
    struct gravity_gpu_values_recv *gravity_gpu_values_recv_d,
    const int *counts_d,
    const int *offsets_d,
    const int *active_counts_d,
    const int *active_offsets_d,
    const int *active_index_d,
    const float *rmax_d,
    float r_s_inv,
    int periodic,
    float min_trunc,
    int ncells,
    int max_cell_size) {

  const int cell = blockIdx.x;
  if (cell >= ncells) return;

  const int counts = counts_d[cell];
  const int cell_offset = offsets_d[cell];
  if (counts <= 0) return;

  /* This kernel handles:
     - all non-periodic self cells
     - periodic self cells with rmax <= min_trunc */
  const int use_full = (!periodic) || (rmax_d[cell] <= min_trunc);
  if (!use_full) return;

  const float factor =
      gravity_gpu_values_send_d[cell_offset].flags0.w ? 1.f : 0.f;
  if (factor == 0.f) return;

  const int active_slot = blockIdx.y * blockDim.x + threadIdx.x;
  const int active_count = active_counts_d[cell];
  const int valid_pid = (active_slot < active_count);
  const int active_base = active_offsets_d[cell];
  const int local_pid =
    valid_pid ? active_index_d[active_base + active_slot] : 0;

  float xi = 0.f, yi = 0.f, zi = 0.f, hi = 0.f;

  if (valid_pid) {
    xi = gravity_gpu_values_send_d[cell_offset + local_pid].values_i.x;
    yi = gravity_gpu_values_send_d[cell_offset + local_pid].values_i.y;
    zi = gravity_gpu_values_send_d[cell_offset + local_pid].values_i.z;
    hi = gravity_gpu_values_send_d[cell_offset + local_pid].values_i.w;
  }

  float a_x = 0.f, a_y = 0.f, a_z = 0.f, pot = 0.f;

  extern __shared__ gravity_gpu_values_send send[];

  for (int i0 = 0; i0 < counts; i0 += blockDim.x) {
    const int i = i0 + threadIdx.x;
    if (i < counts) send[threadIdx.x] = gravity_gpu_values_send_d[cell_offset + i];
    __syncthreads();

    const int tile = min(blockDim.x, counts - i0);

    if (valid_pid) {
      for (int j = 0; j < tile; j++) {
        const int pjd = i0 + j;
        if (local_pid == pjd) continue;

        const gravity_gpu_values_send pj = send[j];
        const float mass_i = pj.mass.x;

        const float dx = pj.values_i.x - xi;
        const float dy = pj.values_i.y - yi;
        const float dz = pj.values_i.z - zi;

        const float r2 = dx * dx + dy * dy + dz * dz;
        const float h = max(hi, pj.values_i.w);
        const float h2 = h * h;
        const float h_inv = 1.f / h;
        const float h_inv_3 = h_inv * h_inv * h_inv;

        float f_ij, pot_ij;
        iact_grav_pp_full(r2, h2, h_inv, h_inv_3, mass_i, &f_ij, &pot_ij);

        a_x += f_ij * dx;
        a_y += f_ij * dy;
        a_z += f_ij * dz;
        pot += pot_ij;
      }
    }
    __syncthreads();
  }

  if (valid_pid) {
    const int out = active_base + active_slot;

	gravity_gpu_values_recv_d[out].values_i.x = a_x * factor;
	gravity_gpu_values_recv_d[out].values_i.y = a_y * factor;
	gravity_gpu_values_recv_d[out].values_i.z = a_z * factor;
	gravity_gpu_values_recv_d[out].values_i.w = pot * factor;
  }
}

/**
 * @brief Compute truncated self-cell P-P gravity interactions using shared-memory tiling.
 *
 * This kernel is the tiled variant of the self-cell truncated-force interaction,
 * reusing source-particle data from shared memory to reduce global memory traffic.
 *
 * @param gravity_gpu_values_send_d Device input buffer for packed particles.
 * @param gravity_gpu_values_recv_d Device output buffer for accelerations and potential.
 * @param r_s_inv Inverse splitting scale for long-range correction.
 * @param gcount_i Number of particles in the cell.
 * @param gcount_padded_i Padded particle count in the cell.
 * @param periodic Whether periodic boundary conditions are enabled.
 * @param max_r_decision Whether the truncated interaction path should be used.
 * @param ncells Number of packed cells in the batch.
 */
__global__ void doself_grav_pp_truncated_new_refactor_tiled(
    struct gravity_gpu_values_send *gravity_gpu_values_send_d,
    struct gravity_gpu_values_recv *gravity_gpu_values_recv_d,
    const int *counts_d,
    const int *offsets_d,
    const int *active_counts_d,
    const int *active_offsets_d,
    const int *active_index_d,
    const float *rmax_d,
    float r_s_inv,
    const int periodic,
    float min_trunc,
    int ncells) {

  const int cell = blockIdx.x;
  if (cell >= ncells) return;

  const int counts = counts_d[cell];
  const int cell_offset = offsets_d[cell];
  if (counts <= 0) return;

  /* This kernel handles only periodic self cells with rmax > min_trunc */
  const int use_truncated = periodic && (rmax_d[cell] > min_trunc);
  if (!use_truncated) return;

  const float factor =
      gravity_gpu_values_send_d[cell_offset].flags0.w ? 1.f : 0.f;
  if (factor == 0.f) return;

  const int active_slot = blockIdx.y * blockDim.x + threadIdx.x;
  const int active_count = active_counts_d[cell];
  const int valid_pid = (active_slot < active_count);
  const int active_base = active_offsets_d[cell];

  const int pid = valid_pid ? active_index_d[active_base + active_slot] : 0;

  float xi = 0.f, yi = 0.f, zi = 0.f, hi = 0.f;

  if (valid_pid) {
    xi = gravity_gpu_values_send_d[cell_offset + pid].values_i.x;
    yi = gravity_gpu_values_send_d[cell_offset + pid].values_i.y;
    zi = gravity_gpu_values_send_d[cell_offset + pid].values_i.z;
    hi = gravity_gpu_values_send_d[cell_offset + pid].values_i.w;
  }

  float a_x = 0.f, a_y = 0.f, a_z = 0.f, pot = 0.f;

  extern __shared__ gravity_gpu_values_send send[];

  for (int i0 = 0; i0 < counts; i0 += blockDim.x) {
    const int i = i0 + threadIdx.x;

    if (i < counts) {
      send[threadIdx.x] = gravity_gpu_values_send_d[cell_offset + i];
    }

    __syncthreads();

    const int tile = min(blockDim.x, counts - i0);

    if (valid_pid) {
      for (int j = 0; j < tile; j++) {
        const int pjd = i0 + j;
        if (pid == pjd) continue;

        const gravity_gpu_values_send pj = send[j];
        const float mass_i = pj.mass.x;

        const float dx = pj.values_i.x - xi;
        const float dy = pj.values_i.y - yi;
        const float dz = pj.values_i.z - zi;

        const float r2 = dx * dx + dy * dy + dz * dz;
        const float h = max(hi, pj.values_i.w);
        const float h2 = h * h;
        const float h_inv = 1.f / h;
        const float h_inv_3 = h_inv * h_inv * h_inv;

        float f_ij, pot_ij;
        iact_grav_pp_truncated(
            r2, h2, h_inv, h_inv_3, mass_i, r_s_inv, &f_ij, &pot_ij);

        a_x += f_ij * dx;
        a_y += f_ij * dy;
        a_z += f_ij * dz;
        pot += pot_ij;
      }
    }

    __syncthreads();
  }

  if (valid_pid) {
    const int out = active_base + active_slot;

    gravity_gpu_values_recv_d[out].values_i.x = a_x * factor;
    gravity_gpu_values_recv_d[out].values_i.y = a_y * factor;
    gravity_gpu_values_recv_d[out].values_i.z = a_z * factor;
    gravity_gpu_values_recv_d[out].values_i.w = pot * factor;
  }
}

